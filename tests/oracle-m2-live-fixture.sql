CREATE TABLE m2_parent (
  parent_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
  code VARCHAR2(30) NOT NULL,
  description VARCHAR2(200) DEFAULT 'technical fixture',
  payload CLOB,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT m2_parent_pk PRIMARY KEY (parent_id),
  CONSTRAINT m2_parent_code_uq UNIQUE (code),
  CONSTRAINT m2_parent_code_ck CHECK (LENGTH(code) >= 2)
);

CREATE TABLE m2_child (
  child_id NUMBER PRIMARY KEY,
  parent_id NUMBER NOT NULL,
  status VARCHAR2(20) NOT NULL,
  amount NUMBER(12,2),
  CONSTRAINT m2_child_parent_fk FOREIGN KEY (parent_id) REFERENCES m2_parent(parent_id),
  CONSTRAINT m2_child_status_ck CHECK (status IN ('OPEN','CLOSED'))
);

CREATE TABLE m2_range_part (
  bucket_date DATE NOT NULL,
  bucket_id NUMBER NOT NULL,
  payload VARCHAR2(50),
  CONSTRAINT m2_range_part_pk PRIMARY KEY (bucket_date, bucket_id)
)
PARTITION BY RANGE (bucket_date) (
  PARTITION p_2026_01 VALUES LESS THAN (DATE '2026-02-01'),
  PARTITION p_max VALUES LESS THAN (MAXVALUE)
);

CREATE INDEX m2_child_status_ix ON m2_child(status);
CREATE SEQUENCE m2_demo_seq START WITH 100 INCREMENT BY 5 CACHE 20;
CREATE OR REPLACE VIEW m2_parent_v AS SELECT parent_id, code, created_at FROM m2_parent;
CREATE MATERIALIZED VIEW m2_parent_mv BUILD IMMEDIATE REFRESH COMPLETE ON DEMAND AS SELECT parent_id, code FROM m2_parent;
CREATE SYNONYM m2_parent_syn FOR m2_parent;
