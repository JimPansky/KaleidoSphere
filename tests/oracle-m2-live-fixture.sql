/

CREATE OR REPLACE PACKAGE BODY m2_pkg AS
  FUNCTION normalize_code(p_code IN VARCHAR2 DEFAULT 'NA') RETURN VARCHAR2 IS
  BEGIN
    RETURN UPPER(TRIM(p_code));
  END;

  PROCEDURE touch_parent(p_parent_id IN NUMBER) IS
  BEGIN
    NULL;
  END;
END m2_pkg;
/

CREATE OR REPLACE FUNCTION m2_status_label(p_status IN VARCHAR2) RETURN VARCHAR2 IS
BEGIN
  RETURN CASE p_status WHEN 'OPEN' THEN 'Open' WHEN 'CLOSED' THEN 'Closed' ELSE 'Unknown' END;
END;
